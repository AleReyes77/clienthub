import { randomUUID } from "node:crypto";
import { createReadStream } from "node:fs";
import { mkdir, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { Readable } from "node:stream";
import {
  DeleteObjectCommand,
  GetObjectCommand,
  PutObjectCommand,
  S3Client,
} from "@aws-sdk/client-s3";
import { notFound } from "./errors.js";

/** Where file bytes live. Metadata (name, size, owner) is stored in PostgreSQL. */
export interface Storage {
  put(key: string, body: Buffer, contentType: string): Promise<void>;
  get(key: string): Promise<Readable>;
  delete(key: string): Promise<void>;
}

/**
 * Keys are always generated by the server (never from the uploaded filename),
 * which rules out path traversal like "../../etc/passwd".
 */
export function newStorageKey(prefix: string): string {
  return `${prefix}/${randomUUID()}`;
}

const SAFE_KEY = /^[a-z0-9][a-z0-9/_-]{0,200}$/i;

function assertSafeKey(key: string) {
  if (!SAFE_KEY.test(key) || key.includes("..")) throw new Error(`Invalid storage key: ${key}`);
}

/** Stores files on the local disk. Fine for development and single-server setups. */
export function createLocalStorage(rootDir: string): Storage {
  const root = path.resolve(rootDir);

  function resolve(key: string) {
    assertSafeKey(key);
    const filePath = path.resolve(root, key);
    // Defense in depth: the resolved path must stay inside the upload directory.
    if (!filePath.startsWith(root + path.sep)) throw new Error(`Invalid storage key: ${key}`);
    return filePath;
  }

  return {
    async put(key, body) {
      const filePath = resolve(key);
      await mkdir(path.dirname(filePath), { recursive: true });
      await writeFile(filePath, body, { flag: "wx" });
    },
    async get(key) {
      const filePath = resolve(key);
      try {
        await stat(filePath);
      } catch {
        throw notFound("File");
      }
      return createReadStream(filePath);
    },
    async delete(key) {
      await rm(resolve(key), { force: true });
    },
  };
}

export interface S3StorageOptions {
  bucket: string;
  region: string;
  endpoint?: string | undefined;
  accessKeyId?: string | undefined;
  secretAccessKey?: string | undefined;
  forcePathStyle?: boolean;
}

/** Any S3-compatible object storage (AWS S3, Cloudflare R2, MinIO…). */
export function createS3Storage(options: S3StorageOptions): Storage {
  const client = new S3Client({
    region: options.region,
    ...(options.endpoint ? { endpoint: options.endpoint } : {}),
    forcePathStyle: options.forcePathStyle ?? false,
    ...(options.accessKeyId && options.secretAccessKey
      ? {
          credentials: {
            accessKeyId: options.accessKeyId,
            secretAccessKey: options.secretAccessKey,
          },
        }
      : {}),
  });

  return {
    async put(key, body, contentType) {
      assertSafeKey(key);
      await client.send(
        new PutObjectCommand({
          Bucket: options.bucket,
          Key: key,
          Body: body,
          ContentType: contentType,
        }),
      );
    },
    async get(key) {
      assertSafeKey(key);
      try {
        const result = await client.send(
          new GetObjectCommand({ Bucket: options.bucket, Key: key }),
        );
        if (!(result.Body instanceof Readable)) throw notFound("File");
        return result.Body;
      } catch (error) {
        if (error instanceof Error && error.name === "NoSuchKey") throw notFound("File");
        throw error;
      }
    },
    async delete(key) {
      assertSafeKey(key);
      await client.send(new DeleteObjectCommand({ Bucket: options.bucket, Key: key }));
    },
  };
}
